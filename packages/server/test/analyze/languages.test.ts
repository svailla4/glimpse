import {describe, expect, it} from 'vitest';
import {extName, hasGeneratedHeader, isBinaryExt, isGeneratedPath, isTestPath, languageOf} from '../../src/analyze/languages.ts';

describe('languageOf', () => {
  it.each([
    ['src/a.ts', 'TypeScript', 'ts'],
    ['src/App.tsx', 'TypeScript', 'ts'],
    ['lib/x.mjs', 'JavaScript', 'ts'],
    ['tools/cli.py', 'Python', 'py'],
    ['cmd/main.go', 'Go', 'go'],
    ['src/lib.rs', 'Rust', 'rs'],
    ['A.java', 'Java', 'java'],
    ['build.gradle.kts', 'Kotlin', 'kt'],
    ['app/models/user.rb', 'Ruby', 'rb'],
    ['Program.cs', 'C#', 'cs'],
    ['index.php', 'PHP', 'php'],
    ['App.swift', 'Swift', 'swift'],
    ['lib/main.dart', 'Dart', 'dart'],
    ['include/x.hpp', 'C++', 'c'],
  ])('%s is %s with %s patterns', (path, name, scan) => {
    expect(languageOf(path)).toMatchObject({name, kind: 'code', scan});
  });

  it('knows file names and falls back to the extension', () => {
    expect(languageOf('Dockerfile')?.name).toBe('Dockerfile');
    expect(languageOf('docker/Dockerfile.prod')?.name).toBe('Dockerfile');
    expect(languageOf('Makefile')?.name).toBe('Makefile');
    expect(languageOf('Gemfile')).toMatchObject({name: 'Ruby', scan: 'rb'});
    expect(languageOf('go.mod')?.name).toBe('Go Module');
    expect(languageOf('.env.local')?.name).toBe('INI');
    expect(languageOf('README.md')).toMatchObject({name: 'Markdown', kind: 'prose'});
    expect(languageOf('data/x.JSON')).toMatchObject({name: 'JSON', kind: 'data'});
  });

  it('languages without patterns are still named; unknown files are not', () => {
    expect(languageOf('lib/app.ex')).toEqual({name: 'Elixir', kind: 'code', comments: 'hash'});
    expect(languageOf('weird.xyz')).toBeUndefined();
    expect(languageOf('LICENSE')).toBeUndefined();
    expect(languageOf('.hidden')).toBeUndefined();
  });

  it('extName ignores dotfiles and directories with dots', () => {
    expect(extName('a.b/c')).toBe('');
    expect(extName('.gitignore')).toBe('');
    expect(extName('x/y.Min.JS')).toBe('js');
  });
});

describe('path classes', () => {
  it.each([
    'test/auth.test.ts', 'src/__tests__/a.ts', 'tests/unit/a.py', 'spec/models/user_spec.rb', 'pkg/limiter/limiter_test.go',
    'tools/tests/test_stats.py', 'tools/test_cli.py', 'src/a.spec.tsx', 'app/src/test/java/FooTest.java', 'Sources/AppTests.swift',
  ])('%s is a test', path => {
    expect(isTestPath(path)).toBe(true);
  });

  it.each(['src/contest/a.ts', 'src/latest.ts', 'src/testing.py', 'src/attest.go', 'Sources/Contest.swift', 'spec.md'])('%s is not a test', path => {
    expect(isTestPath(path)).toBe(false);
  });

  it.each([
    'package-lock.json', 'web/yarn.lock', 'Cargo.lock', 'go.sum', 'dist/app.js', 'pkg/build/out.js', 'vendor/github.com/x/y.go', 'web/app.min.js',
    'api/v1/service.pb.go', 'src/schema.generated.ts', 'src/__snapshots__/a.test.ts.snap', 'lib/model.g.dart', 'proto/a_pb2.py', 'node_modules/x/index.js',
  ])('%s is generated', path => {
    expect(isGeneratedPath(path)).toBe(true);
  });

  it.each(['src/builder.ts', 'src/distance.ts', 'docs/build.md', 'src/vendors.ts', 'src/admin.ts', 'lock.ts'])('%s is not generated', path => {
    expect(isGeneratedPath(path)).toBe(false);
  });

  it('recognises generated-file headers', () => {
    expect(hasGeneratedHeader('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x')).toBe(true);
    expect(hasGeneratedHeader('/**\n * @generated SignedSource<<abc>>\n */')).toBe(true);
    expect(hasGeneratedHeader('// GENERATED CODE - DO NOT MODIFY BY HAND')).toBe(true);
    expect(hasGeneratedHeader('// This module generates code for others.')).toBe(false);
  });

  it('binary extensions are never read', () => {
    expect(isBinaryExt('img/logo.PNG')).toBe(true);
    expect(isBinaryExt('fonts/a.woff2')).toBe(true);
    expect(isBinaryExt('src/a.ts')).toBe(false);
    expect(isBinaryExt('png')).toBe(false);
  });
});
